#!/usr/bin/env python3
"""Write js/assets.js: a short content hash for every file in tex/, snd/ and fonts/.

Why: vercel.json caches these folders for a year as immutable. Without a version in the URL,
a phone that saw an old painting keeps showing it after a deploy (that caused the letter-beat seam).
Run this before every push:  python3 tools/stamp.py
"""
import hashlib, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = {}
for d in ('tex', 'snd', 'fonts'):
    for n in sorted(os.listdir(os.path.join(ROOT, d))):
        p = os.path.join(ROOT, d, n)
        if os.path.isfile(p):
            V[f'{d}/{n}'] = hashlib.md5(open(p, 'rb').read()).hexdigest()[:8]
src = ('// generated by tools/stamp.py - do not edit. Run it before every push.\n'
       f'export const V = {json.dumps(V, indent=0, sort_keys=True)};\n'
       "export const asset = (p) => { const k = p.replace(/^\\//, ''); return '/' + k + (V[k] ? '?v=' + V[k] : ''); };\n")
open(os.path.join(ROOT, 'js', 'assets.js'), 'w').write(src)
print('stamped', len(V), 'files')
